// All seven selected declaration types, including FUNCTION itself. Caller
// supplies normalized name. Non-ASCII locale and escaped-name lowering unknown.
// An enabled nonmatching category DOES NOT stop later categories being checked.
// First matching enabled category wins: VHDL, Verilog, SV, SDF/EDIF, PSL, Windows.
// NoMatch covers this explicit ASCII predicate only, never the whole standard.
[[nodiscard]] inline VerilogKeywordResult checkVerilogKeywordName(
    std::string_view normalizedName, VerilogNamingShapeSubject subject,
    const VerilogKeywordPolicy& policy) {
    if (!policy.configurationKnown) return {};
    if (subject==VerilogNamingShapeSubject::Unsupported)
        return {VerilogKeywordStatus::Unsupported, std::nullopt};
    std::string name(normalizedName);
    for (auto& c:name) {
        const auto byte=static_cast<unsigned char>(c);
        if (byte==0 || byte>=128) return {VerilogKeywordStatus::Unsupported, std::nullopt};
        if (c>='A' && c<='Z') c=static_cast<char>(c-'A'+'a');
    }
    // Native empty string skips its category chain.
    if (name.empty()) return {VerilogKeywordStatus::NoMatch, std::nullopt};
    for (std::size_t i=0; i<policy.enabled.size(); ++i) {
        const auto category=static_cast<VerilogKeywordCategory>(i);
        if (policy.enabled[i] && keyword_tables::contains(category, name))
            return {VerilogKeywordStatus::Matched, category};
    }
    return {VerilogKeywordStatus::NoMatch, std::nullopt};
}
