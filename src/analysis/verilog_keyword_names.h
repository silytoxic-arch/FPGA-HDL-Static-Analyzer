[[nodiscard]] inline bool contains(VerilogKeywordCategory category, std::string_view name) {
    const auto in=[&](const auto& table) {
        for (const auto key:table) if (key==name) return true;
        return false;
    };
    switch(category) {
    case VerilogKeywordCategory::Vhdl: return in(Vhdl);
    case VerilogKeywordCategory::Verilog: return in(Verilog);
    case VerilogKeywordCategory::SystemVerilog: return in(SystemVerilog);
    case VerilogKeywordCategory::SdfEdif: return in(SdfEdif);
    case VerilogKeywordCategory::Psl: return in(Psl);
    case VerilogKeywordCategory::Windows: return in(Windows);
    }
    return false;
}
