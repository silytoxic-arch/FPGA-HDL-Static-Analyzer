[[nodiscard]] inline std::string nativeVerilogKeywordMessage(
    VerilogKeywordCategory category, std::string_view normalizedName) {
    return std::string(NativeVerilogKeywordMessagePrefixes[
        static_cast<std::size_t>(category)]) + std::string(normalizedName);
}
[[nodiscard]] inline std::optional<VerilogKeywordCategory> parseVerilogKeywordCategory(std::string_view name) {
    for (std::size_t i=0; i<VerilogKeywordCategoryNames.size(); ++i)
        if (name==VerilogKeywordCategoryNames[i]) return static_cast<VerilogKeywordCategory>(i);
    return std::nullopt;
}
